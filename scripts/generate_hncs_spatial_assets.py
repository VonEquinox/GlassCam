#!/usr/bin/env python3
"""Regenerate portable spatial preset rows and exact SciPy Gaussian weights.

Uses the chosen GlassCam Python reference and locally installed NumPy/SciPy.
The C++ runtime has no dependency on either package.
"""
import argparse, hashlib, importlib.util, pathlib
import numpy as np
from scipy.ndimage._filters import _gaussian_kernel1d
from phocus_sharpness_settings import preset_sharpness


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--reference',type=pathlib.Path,required=True)
    ap.add_argument('--output',type=pathlib.Path,default=pathlib.Path(__file__).resolve().parents[1]/'core/hncs_spatial_assets.inc')
    args=ap.parse_args()
    spec=importlib.util.spec_from_file_location('spatial_reference',args.reference/'phocus_presets.py')
    p=importlib.util.module_from_spec(spec); spec.loader.exec_module(p)
    records=[]; kernels={}
    def kernel(sigma):
        name='kGaussian'+str(len(kernels))
        if sigma not in kernels: kernels[sigma]=(name,_gaussian_kernel1d(sigma,0,int(4.*sigma+.5)))
        return kernels[sigma][0]
    for key in sorted(set(p.preset_key(k) for k in p.PRESET_CHOICES)):
        s=p.settings(key);g=s['film_grain'];sh=s['sharpness']
        active=bool(g.get('ApplyFilmGrain') and g.get('FilmGrainAmount'))
        amount=float(g.get('FilmGrainAmount') or 0)/100
        color=float(g.get('FilmGrainColor') or 0)/100
        rough=float(g.get('FilmGrainRoughness') or 0)/100
        size=float(g.get('FilmGrainSize') or 0)/100
        gt=int(g.get('FilmGrainType') or 0)
        fine=max(.15,.35+.8*size+.15*gt);coarse=max(.5,1.3+3*size+.35*gt)
        usm=float(sh.get('amount') or 0)/100
        radius=max(float(sh.get('radius') if sh.get('radius') is not None else 10)/10,.1)
        thresh=float(sh.get('noise_limit') or 0)/65535
        records.append((key,active,amount,color,rough,fine,coarse,usm,radius,thresh,
                        kernel(fine) if active else None,kernel(coarse) if active else None,kernel(radius) if usm else None))
    out=['// Generated by scripts/generate_hncs_spatial_assets.py. Do not edit.',
         '// Source phocus_presets.py SHA256: '+hashlib.sha256((args.reference/'phocus_presets.py').read_bytes()).hexdigest(),
         '// Weights: SciPy Gaussian order 0, radius=int(4*sigma+0.5); exact Float64 values.']
    for sigma,(name,arr) in kernels.items():
        out.append(f'static constexpr double {name}[] = {{'+','.join(float(x).hex() for x in arr)+'};')
    out.append('static constexpr SpatialPreset kSpatialPresets[] = {')
    for key,active,a,c,r,fs,cs,u,rad,t,fk,ck,uk in records:
        def kern(k):return '{'+(k+',sizeof('+k+')/sizeof(double)' if k else 'nullptr,0')+'}'
        out.append('{"'+key+'",'+','.join(['true' if active else 'false',repr(a),repr(c),repr(r),repr(u),repr(t),kern(fk),kern(ck),kern(uk)])+'},')
    out.append('};')
    out.append('static constexpr NativeSharpnessPreset kNativeSharpnessPresets[] = {')
    for key in sorted(set(p.preset_key(k) for k in p.PRESET_CHOICES)):
        sharp=preset_sharpness(p,key)
        out.append('{"'+key+'",'+','.join([
            'true' if sharp['enabled'] else 'false',str(sharp['amount']),
            repr(sharp['radius']/10.),str(sharp['noise_limit']),str(sharp['dark_limit'])])+'},')
    out.append('};')
    args.output.write_text('\n'.join(out)+'\n')
    print(f'Wrote {len(records)} presets, {len(kernels)} kernels to {args.output}')
if __name__=='__main__':main()
